enum view_kind { VIEW_CBV, VIEW_SRV, VIEW_UAV, VIEW_RTV, VIEW_DSV, VIEW_SAMPLER, VIEW_SAMPLER2 };

/* OP_CREATE_RESOURCE variants, named after the D3D12 method they map to */
